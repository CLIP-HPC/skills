#!/usr/bin/env python3
"""Generate host adapters from portable manifests and shared skill metadata."""
import argparse
import json
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"


def load_json(path):
    return json.loads(path.read_text())


def skill_metadata(path):
    text = path.read_text()
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: missing YAML frontmatter")
    parts = text.split("\n---\n", 1)
    if len(parts) != 2:
        raise ValueError(f"{path}: unterminated YAML frontmatter")
    data = yaml.safe_load(parts[0][4:])
    if not isinstance(data, dict):
        raise ValueError(f"{path}: frontmatter must be a mapping")
    return data


def inside(root, relative):
    if not isinstance(relative, str) or not relative.startswith("./"):
        raise ValueError(f"Expected a ./-prefixed path: {relative!r}")
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError(f"Path escapes repository: {relative}")
    return path


def json_text(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def generated_files(root):
    root = root.resolve()
    catalog = load_json(root / "marketplace.json")
    outputs = {}
    entries = []
    for entry in catalog["plugins"]:
        source = entry["source"]
        if isinstance(source, dict):
            entries.append(entry)
            continue
        folder = inside(root, source)
        manifest = load_json(folder / "plugin.json")
        # Only shared identity fields are copied. Portable extensions stay portable.
        compatibility = {key: value for key, value in manifest.items()
                         if key not in {"$schema", "extensions"}}
        outputs[folder / ".claude-plugin/plugin.json"] = json_text(compatibility)
        shared = {"name": manifest["name"], "description": manifest["description"],
                  "category": entry["category"]}
        entries.append({**shared, "source": source})
        for skill in sorted((folder / "skills").glob("*/SKILL.md")):
            data = skill_metadata(skill)
            metadata = data["metadata"]
            interface = {
                "display_name": metadata["display-name"],
                "short_description": metadata["short-description"],
                "default_prompt": f"Use ${data['name']} to {metadata['example-task']}",
            }
            # JSON strings are YAML-compatible; quote every interface string.
            outputs[skill.parent / "agents/openai.yaml"] = (
                "# Generated by scripts/bundle.py; edit SKILL.md metadata instead.\n"
                "interface:\n" + "".join(
                    f"  {key}: {json.dumps(value, ensure_ascii=False)}\n"
                    for key, value in interface.items()))
    outputs[root / ".claude-plugin/marketplace.json"] = json_text({
        "name": catalog["name"], "owner": catalog["owner"],
        "metadata": {"description": catalog["description"]},
        "plugins": entries,
    })
    outputs[root / ".agents/plugins/marketplace.json"] = json_text({
        "name": catalog["name"], "interface": {"displayName": catalog["display_name"]},
        "plugins": [{**entry, "policy": {"installation": "AVAILABLE",
                                         "authentication": "ON_INSTALL"}}
                    for entry in entries],
    })
    return outputs


def generate(root, check=False):
    root = root.resolve()
    stale = []
    for path, expected in generated_files(root).items():
        if not path.exists() or path.read_text() != expected:
            stale.append(path.relative_to(root))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    if check and stale:
        raise ValueError("Generated files are stale: " + ", ".join(map(str, stale))
                         + ". Run uv run python scripts/bundle.py.")
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on generated-file drift")
    args = parser.parse_args()
    try:
        changed = generate(ROOT, args.check)
    except (ValueError, KeyError, OSError, yaml.YAMLError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print("Generated files are current." if args.check else f"Updated {len(changed)} generated files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
